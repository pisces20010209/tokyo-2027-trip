def _build_candidates(prefix: str, groups: dict) -> list:
    items = []
    counter = 1
    for area, names in groups.items():
        for name in names:
            items.append({"id": f"{prefix}{counter:03d}", "area": area, "name": name})
            counter += 1
    return items


