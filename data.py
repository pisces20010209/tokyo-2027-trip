    for region, categories in regions.items():
        for category, restaurants in categories.items():
            for r in restaurants:
                items.append(
                    {
                        "id": f"f{counter:03d}",
                        "region": region,
                        "category": category,
                        "name": r[0],
                        "location": r[1],
                        "note": r[2],
                    }
                )
                counter += 1
    return items


